create or replace function public.save_assessment_configuration(
  p_sections jsonb,
  p_topics jsonb,
  p_subtopics jsonb,
  p_additional_topics jsonb,
  p_questions jsonb,
  p_expected_version bigint,
  p_removed_topic_ids jsonb default '[]'::jsonb,
  p_removed_subtopic_ids jsonb default '[]'::jsonb,
  p_removed_additional_topic_ids jsonb default '[]'::jsonb,
  p_removed_question_codes jsonb default '[]'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_version bigint;
  v_current_version bigint;
begin
  if auth.uid() is null or coalesce(public.current_user_role_canonical(), '') not in ('super_user', 'developer') then
    raise exception 'Only administrators can save assessment configuration.' using errcode = '42501';
  end if;
  if p_sections is null or p_topics is null or p_subtopics is null or p_additional_topics is null
    or p_questions is null or p_removed_topic_ids is null or p_removed_subtopic_ids is null
    or p_removed_additional_topic_ids is null or p_removed_question_codes is null
    or jsonb_typeof(p_sections) <> 'array' or jsonb_typeof(p_topics) <> 'array'
    or jsonb_typeof(p_subtopics) <> 'array' or jsonb_typeof(p_additional_topics) <> 'array'
    or jsonb_typeof(p_questions) <> 'array'
    or jsonb_typeof(p_removed_topic_ids) <> 'array'
    or jsonb_typeof(p_removed_subtopic_ids) <> 'array'
    or jsonb_typeof(p_removed_additional_topic_ids) <> 'array'
    or jsonb_typeof(p_removed_question_codes) <> 'array' then
    raise exception 'Configuration payloads must be JSON arrays.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_sections) > 100 or jsonb_array_length(p_topics) > 10000
    or jsonb_array_length(p_subtopics) > 10000 or jsonb_array_length(p_additional_topics) > 10000
    or jsonb_array_length(p_questions) > 50000 then
    raise exception 'Configuration payload exceeds the allowed size.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_sections) = 0 or jsonb_array_length(p_topics) = 0 or jsonb_array_length(p_questions) = 0 then
    raise exception 'At least one section, topic, and question are required.' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('assessment-configuration-version', 0));
  select current_version into v_current_version
  from public.assessment_configuration_state where singleton for update;
  if p_expected_version is null or p_expected_version <> v_current_version then
    raise exception 'Assessment configuration changed since it was loaded. Reload it before saving.'
      using errcode = '40001';
  end if;
  perform public.validate_question_configuration_payload(p_questions);

create or replace view public.assessment_question_scores as
with baseline_answers as (
  select distinct on (answer.ranch_name, answer.block_number, answer.question_code)
    answer.ranch_name, answer.block_number, answer.question_code, answer.response
  from public.answers answer
  join public.assessment_submissions submission
    on submission.user_id = answer.user_id and submission.ranch_name = answer.ranch_name
   and submission.block_number = answer.block_number and submission.phase = 1
   and submission.assessor_slot = 1 and submission.status = 'submitted'
  where answer.phase = 1
  order by answer.ranch_name, answer.block_number, answer.question_code, answer.submitted_at desc
), submitted_answers as (
  select
    answer.user_id, answer.ranch_name, answer.block_number, answer.phase, answer.assessor_slot,
    answer.question_code, answer.response, question.question_type, question.is_survey,
    question.max_score, question.total_count, question.score_ranges, question.objective_options,
    question.scoring_parent_code, question.scoring_direction, question.percentage_thresholds,
    question.code, baseline.response as baseline_response,
    parent_baseline.response as baseline_parent_response
  from public.answers answer
  join public.assessment_submissions submission
    on submission.user_id = answer.user_id and submission.ranch_name = answer.ranch_name
   and submission.block_number = answer.block_number and submission.phase = answer.phase
   and submission.assessor_slot = answer.assessor_slot and submission.status = 'submitted'
  join public.assessment_configuration_questions question
    on question.version = submission.configuration_version and question.code = answer.question_code
  left join baseline_answers baseline
    on baseline.ranch_name = answer.ranch_name and baseline.block_number = answer.block_number
   and baseline.question_code = answer.question_code
  left join baseline_answers parent_baseline
    on parent_baseline.ranch_name = answer.ranch_name and parent_baseline.block_number = answer.block_number
   and parent_baseline.question_code = question.scoring_parent_code
  where answer.phase in (1, 2)
    and question.active
    and (answer.phase = 1 or exists (
      select 1 from public.juror_topic_assignments assignment
      where assignment.user_id = answer.user_id and assignment.topic_id = question.topic_id
        and assignment.assessor_slot = answer.assessor_slot
    ))
), scored_answers as (
  select
    user_id, ranch_name, block_number, phase, assessor_slot, question_code, question_type,
    max_score, objective_options,
    case
      when is_survey or question_type = 'subjective_single' then null::numeric
      when question_type in ('subjective', 'dynamic_table') and phase = 1 then null::numeric
      when question_type in ('subjective', 'dynamic_table') and phase = 2
        then least(greatest((response ->> code)::numeric, 0), max_score)
      when question_type = 'objective' then
        (select nullif(option.value ->> 'score', '')::numeric
          from jsonb_array_elements(objective_options) as option(value)
          where option.value ->> 'id' = response ->> code limit 1)
      when question_type = 'quantitative' and scoring_parent_code is not null then
        public.chained_percentage_score(
          nullif(response ->> code, '')::numeric,
          nullif(baseline_parent_response ->> scoring_parent_code, '')::numeric,
          max_score, scoring_direction, percentage_thresholds
        )
      when question_type = 'quantitative' then
        least((response ->> code)::numeric,
          coalesce(nullif(case when phase = 1 then response ->> (code || '-target')
            else baseline_response ->> (code || '-target') end, '')::numeric, total_count, 1))
        / coalesce(nullif(case when phase = 1 then response ->> (code || '-target')
          else baseline_response ->> (code || '-target') end, '')::numeric, total_count, 1) * max_score
      when phase = 1 and question_type in ('qualitative', 'qualitative_with_note', 'auto_calculated_financial') then
        case when response ->> (code || '-yn') = 'Ya' then (response ->> code)::numeric / 5 * max_score else 0 end
      when phase = 1 and question_type = 'qualitative_range' and response ->> (code || '-yn') = 'Ya' then
        (select (band.range_value ->> 'score')::numeric / 5 * max_score
          from jsonb_array_elements(score_ranges) as band(range_value)
          where (response ->> code)::numeric >= (band.range_value ->> 'min')::numeric
            and ((band.range_value ->> 'max') is null or (response ->> code)::numeric <= (band.range_value ->> 'max')::numeric)
          limit 1)
      when phase = 1 then case when coalesce(response ->> (code || '-yn'), response ->> code) = 'Ya' then max_score else 0 end
      when question_type in ('qualitative_no_grade', 'qualitative_note_only') then
        case when response ->> (code || '-yn') = 'Ya' then max_score else 0 end
      when question_type = 'qualitative_range' and response ->> (code || '-yn') = 'Ya' then
        (select (band.range_value ->> 'score')::numeric / 5 * max_score
          from jsonb_array_elements(score_ranges) as band(range_value)
          where (response ->> code)::numeric >= (band.range_value ->> 'min')::numeric
            and ((band.range_value ->> 'max') is null or (response ->> code)::numeric <= (band.range_value ->> 'max')::numeric)
          limit 1)
      when response ->> (code || '-yn') = 'Ya' then (response ->> code)::numeric / 5 * max_score
      else 0
    end as score_marks
  from submitted_answers
)
select phase, ranch_name, block_number, question_code, assessor_slot, question_type,
  score_marks, max_score,
  case when score_marks is null then null else round(score_marks / nullif(max_score, 0) * 100, 2) end as score_percent
from scored_answers;

create or replace function public.validate_question_configuration_payload(p_questions jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_question jsonb;
  v_type text;
  v_maximum numeric;
  v_is_survey boolean;
  v_invalid integer;
begin
  if jsonb_typeof(p_questions) <> 'array' then
    raise exception 'Questions must be provided as a JSON array.' using errcode = '22023';
  end if;
  for v_question in select value from jsonb_array_elements(p_questions)
  loop
    if jsonb_typeof(v_question) <> 'object'
      or nullif(btrim(v_question ->> 'code'), '') is null
      or nullif(btrim(v_question ->> 'prompt'), '') is null then
      raise exception 'Each question requires a code and prompt.' using errcode = '22023';
    end if;
    v_type := v_question ->> 'question_type';
    v_maximum := nullif(v_question ->> 'max_score', '')::numeric;
    v_is_survey := coalesce((v_question ->> 'is_survey')::boolean, false);
    if v_type not in (
      'qualitative', 'qualitative_no_grade', 'qualitative_with_note', 'qualitative_note_only',
      'qualitative_range', 'objective', 'dynamic_table', 'quantitative', 'subjective',
      'subjective_single', 'auto_calculated_financial'
    ) then
      raise exception 'Question % has an unsupported question type.', v_question ->> 'code' using errcode = '22023';
    end if;
    if v_maximum is null or v_maximum < 0 or v_maximum > 100000
      or (not v_is_survey and v_type <> 'subjective_single' and v_maximum < 1)
      or (v_is_survey and v_maximum <> 0) then
      raise exception 'Question % has an invalid maximum score.', v_question ->> 'code' using errcode = '22023';
    end if;
    if v_type in ('qualitative_with_note', 'qualitative_note_only')
      and nullif(btrim(v_question ->> 'note_prompt'), '') is null then
      raise exception 'Question % requires a note prompt.', v_question ->> 'code' using errcode = '22023';
    end if;

    if v_type = 'objective' then
      if jsonb_typeof(v_question -> 'objective_options') is distinct from 'array' then
        raise exception 'Objective question % requires at least two options.', v_question ->> 'code' using errcode = '22023';
      end if;
      if jsonb_array_length(v_question -> 'objective_options') < 2 then
        raise exception 'Objective question % requires at least two options.', v_question ->> 'code' using errcode = '22023';
      end if;
      select count(*) into v_invalid
      from jsonb_array_elements(v_question -> 'objective_options') option(value)
      where jsonb_typeof(option.value) <> 'object'
        or nullif(btrim(option.value ->> 'id'), '') is null
        or nullif(btrim(option.value ->> 'label'), '') is null
        or length(option.value ->> 'label') > 300
        or coalesce((option.value ->> 'score')::numeric, -1) < 0
        or coalesce((option.value ->> 'score')::numeric, 1000000) > 99999.99;
      if v_invalid > 0 then
        raise exception 'Objective question % contains an invalid option.', v_question ->> 'code' using errcode = '22023';
      end if;
      select count(*) - count(distinct option.value ->> 'id') into v_invalid
      from jsonb_array_elements(v_question -> 'objective_options') option(value);
      if v_invalid > 0 then
        raise exception 'Objective question % contains duplicate option IDs.', v_question ->> 'code' using errcode = '22023';
      end if;
      select count(*) - count(distinct lower(btrim(option.value ->> 'label'))) into v_invalid
      from jsonb_array_elements(v_question -> 'objective_options') option(value);
      if v_invalid > 0 then
        raise exception 'Objective question % contains duplicate option labels.', v_question ->> 'code' using errcode = '22023';
      end if;
      if not v_is_survey and (
        select max((option.value ->> 'score')::numeric)
        from jsonb_array_elements(v_question -> 'objective_options') option(value)
      ) <> v_maximum then
        raise exception 'Objective question % maximum must match its highest option score.', v_question ->> 'code' using errcode = '22023';
      end if;
      if (
        select max((option.value ->> 'score')::numeric)
        from jsonb_array_elements(v_question -> 'objective_options') option(value)
      ) <= 0 then
        raise exception 'Objective question % must award positive marks for at least one option.', v_question ->> 'code' using errcode = '22023';
      end if;
    end if;

    if v_type = 'dynamic_table' then
      if jsonb_typeof(v_question -> 'table_columns') is distinct from 'array' then
        raise exception 'Dynamic table question % requires non-empty column names.', v_question ->> 'code' using errcode = '22023';
      end if;
      if jsonb_array_length(v_question -> 'table_columns') = 0 or exists (
          select 1 from jsonb_array_elements_text(v_question -> 'table_columns') as column_item(value)
          where nullif(btrim(column_item.value), '') is null
        ) then
        raise exception 'Dynamic table question % requires non-empty column names.', v_question ->> 'code' using errcode = '22023';
      end if;
      if coalesce((v_question ->> 'table_rows')::integer, 0) not between 1 and 50 then
        raise exception 'Dynamic table question % must have 1 to 50 rows.', v_question ->> 'code' using errcode = '22023';
      end if;
    end if;

    if v_type = 'qualitative_range' then
      if jsonb_typeof(v_question -> 'score_ranges') is distinct from 'array' then
        raise exception 'Range question % requires at least one scoring range.', v_question ->> 'code' using errcode = '22023';
      end if;
      if jsonb_array_length(v_question -> 'score_ranges') = 0 then
        raise exception 'Range question % requires at least one scoring range.', v_question ->> 'code' using errcode = '22023';
      end if;
      select count(*) into v_invalid
      from jsonb_to_recordset(v_question -> 'score_ranges') as band(minimum integer, maximum integer, score integer, label text)
      where band.minimum is null or band.minimum < 0
        or (band.maximum is not null and band.maximum < band.minimum)
        or band.score is null or band.score not between 1 and 5
        or nullif(btrim(band.label), '') is null;
      if v_invalid > 0 or exists (
        select 1 from (
          select band.minimum, band.maximum,
            lag(band.maximum) over (order by band.minimum) as previous_maximum,
            row_number() over (order by band.minimum) as position
          from jsonb_to_recordset(v_question -> 'score_ranges') as band(minimum integer, maximum integer, score integer, label text)
        ) ranges
        where ranges.position > 1
          and (ranges.previous_maximum is null or ranges.minimum <= ranges.previous_maximum)
      ) then
        raise exception 'Range question % contains invalid or overlapping score ranges.', v_question ->> 'code' using errcode = '22023';
      end if;
    end if;
  end loop;
end;
$$;

revoke all on function public.validate_question_configuration_payload(jsonb) from public, anon, authenticated;


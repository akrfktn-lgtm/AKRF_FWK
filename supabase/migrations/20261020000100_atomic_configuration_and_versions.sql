create or replace function public.record_assessment_configuration_version()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_version bigint;
  v_snapshot jsonb;
begin
  perform pg_advisory_xact_lock(hashtextextended('assessment-configuration-version', 0));

  select coalesce(jsonb_build_object(
    'sections', (select coalesce(jsonb_agg(to_jsonb(item) order by item.sort_order), '[]'::jsonb) from public.sections item),
    'topics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.section_code, item.sort_order), '[]'::jsonb) from public.topics item),
    'subtopics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.topic_id, item.sort_order), '[]'::jsonb) from public.subtopics item),
    'additional_topics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.subtopic_id, item.sort_order), '[]'::jsonb) from public.additional_topics item),
    'questions', (select coalesce(jsonb_agg(to_jsonb(item) order by item.section, item.sort_order), '[]'::jsonb) from public.questions item),
    'financial_line_items', (select coalesce(jsonb_agg(to_jsonb(item) order by item.question_code, item.sort_order), '[]'::jsonb) from public.financial_line_items item),
    'financial_score_thresholds', (select coalesce(jsonb_agg(to_jsonb(item) order by item.min_percent), '[]'::jsonb) from public.financial_score_thresholds item)
  ), '{}'::jsonb) into v_snapshot;

  insert into public.assessment_configuration_versions (created_by, snapshot)
  values (auth.uid(), v_snapshot)
  returning version into v_version;

  insert into public.assessment_configuration_questions (
    version, code, topic_id, question_type, max_score, is_survey, active, total_count,
    score_ranges, objective_options, scoring_parent_code, scoring_direction, percentage_thresholds
  )
  select v_version, item.code, item.topic_id, item.question_type, item.max_score,
    item.is_survey, item.active, item.total_count, coalesce(item.score_ranges, '[]'::jsonb),
    coalesce(item.objective_options, '[]'::jsonb), item.scoring_parent_code, item.scoring_direction,
    coalesce(item.percentage_thresholds, '[]'::jsonb)
  from jsonb_to_recordset(v_snapshot -> 'questions') as item(
    code text, topic_id text, question_type text, max_score numeric, is_survey boolean, active boolean,
    total_count integer, score_ranges jsonb, objective_options jsonb, scoring_parent_code text,
    scoring_direction text, percentage_thresholds jsonb
  );

  insert into public.assessment_configuration_state (singleton, current_version)
  values (true, v_version)
  on conflict (singleton) do update set current_version = excluded.current_version;

  return v_version;
end;
$$;

update public.assessment_configuration_versions version_row
set snapshot = jsonb_build_object(
  'sections', (select coalesce(jsonb_agg(to_jsonb(item) order by item.sort_order), '[]'::jsonb) from public.sections item),
  'topics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.section_code, item.sort_order), '[]'::jsonb) from public.topics item),
  'subtopics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.topic_id, item.sort_order), '[]'::jsonb) from public.subtopics item),
  'additional_topics', (select coalesce(jsonb_agg(to_jsonb(item) order by item.subtopic_id, item.sort_order), '[]'::jsonb) from public.additional_topics item),
  'questions', (select coalesce(jsonb_agg(to_jsonb(item) order by item.section, item.sort_order), '[]'::jsonb) from public.questions item),
  'financial_line_items', (select coalesce(jsonb_agg(to_jsonb(item) order by item.question_code, item.sort_order), '[]'::jsonb) from public.financial_line_items item),
  'financial_score_thresholds', (select coalesce(jsonb_agg(to_jsonb(item) order by item.min_percent), '[]'::jsonb) from public.financial_score_thresholds item)
)
where version_row.version = (select min(version) from public.assessment_configuration_versions)
  and version_row.snapshot = '{}'::jsonb;

insert into public.assessment_configuration_questions (
  version, code, topic_id, question_type, max_score, is_survey, active, total_count,
  score_ranges, objective_options, scoring_parent_code, scoring_direction, percentage_thresholds
)
select version_row.version, item.code, item.topic_id, item.question_type, item.max_score,
  item.is_survey, item.active, item.total_count, coalesce(item.score_ranges, '[]'::jsonb),
  coalesce(item.objective_options, '[]'::jsonb), item.scoring_parent_code, item.scoring_direction,
  coalesce(item.percentage_thresholds, '[]'::jsonb)
from public.assessment_configuration_versions version_row
cross join lateral jsonb_to_recordset(version_row.snapshot -> 'questions') as item(
  code text, topic_id text, question_type text, max_score numeric, is_survey boolean, active boolean,
  total_count integer, score_ranges jsonb, objective_options jsonb, scoring_parent_code text,
  scoring_direction text, percentage_thresholds jsonb
)
where version_row.version = (select current_version from public.assessment_configuration_state where singleton)
on conflict (version, code) do nothing;


create or replace function public.manage_financial_line_item(
  p_action text,
  p_expected_version bigint,
  p_question_code text,
  p_id uuid default null,
  p_label text default null,
  p_kind text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_version bigint;
  v_current_version bigint;
begin
  if auth.uid() is null or coalesce(public.current_user_role_canonical(), '') not in ('super_user', 'developer') then
    raise exception 'Only administrators can manage financial items.' using errcode = '42501';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('assessment-configuration-version', 0));
  select current_version into v_current_version
  from public.assessment_configuration_state where singleton for update;
  if p_expected_version is null or p_expected_version <> v_current_version then
    raise exception 'Configuration changed since the financial items were loaded. Reload and retry.'
      using errcode = '40001';
  end if;
  if p_action = 'add' then
    if p_question_code is null or p_label is null or length(btrim(p_label)) not between 1 and 200
      or p_kind is null or p_kind not in ('income', 'expense')
      or not exists (select 1 from public.questions where code = p_question_code and question_type = 'auto_calculated_financial' and active) then
      raise exception 'Financial item details are invalid.' using errcode = '22023';
    end if;
    insert into public.financial_line_items (question_code, label, kind, sort_order, active)
    select p_question_code, btrim(p_label), p_kind, coalesce(max(sort_order), 0) + 1, true
    from public.financial_line_items where question_code = p_question_code;
  elsif p_action = 'archive' then
    update public.financial_line_items set active = false where id = p_id and active;
    if not found then raise exception 'Financial item was not found or is already archived.' using errcode = 'P0002'; end if;
  else
    raise exception 'Unsupported financial item action.' using errcode = '22023';
  end if;
  v_version := public.record_assessment_configuration_version();
  return v_version;
end;
$$;

create or replace function public.save_financial_score_thresholds(p_thresholds jsonb, p_expected_version bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_version bigint;
  v_count integer;
  v_current_version bigint;
begin
  if auth.uid() is null or coalesce(public.current_user_role_canonical(), '') not in ('super_user', 'developer') then
    raise exception 'Only administrators can save financial score thresholds.' using errcode = '42501';
  end if;
  if p_thresholds is null or jsonb_typeof(p_thresholds) <> 'array' then
    raise exception 'Thresholds must be provided as a JSON array.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_thresholds) = 0 or jsonb_array_length(p_thresholds) > 100 then
    raise exception 'At least one and no more than 100 thresholds are required.' using errcode = '22023';
  end if;
  select count(*) into v_count
  from (
    select band.min, band.max, band.score,
      lag(band.max) over (order by band.min) as previous_max,
      row_number() over (order by band.min) as position
    from jsonb_to_recordset(p_thresholds) as band(min numeric, max numeric, score integer)
  ) ordered
  where ordered.min is null or ordered.min < 0
    or (ordered.max is not null and ordered.max <= ordered.min)
    or ordered.score is null or ordered.score < 1 or ordered.score > 5
    or (ordered.position > 1 and (ordered.previous_max is null or ordered.previous_max > ordered.min));
  if v_count > 0 then
    raise exception 'Financial score thresholds contain invalid values or overlaps.' using errcode = '22023';
  end if;
  if exists (
    select 1 from (
      select max, row_number() over (order by min) as position, count(*) over () as total
      from jsonb_to_recordset(p_thresholds) as band(min numeric, max numeric, score integer)
    ) band where band.position < band.total and band.max is null
  ) then
    raise exception 'Only the final financial threshold may have no maximum.' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('assessment-configuration-version', 0));
  select current_version into v_current_version
  from public.assessment_configuration_state where singleton for update;
  if p_expected_version is null or p_expected_version <> v_current_version then
    raise exception 'Configuration changed since the financial thresholds were loaded. Reload and retry.'
      using errcode = '40001';
  end if;

  delete from public.financial_score_thresholds;
  insert into public.financial_score_thresholds (min_percent, max_percent, score)
  select band.min, band.max, band.score
  from jsonb_to_recordset(p_thresholds) as band(min numeric, max numeric, score integer);

  v_version := public.record_assessment_configuration_version();
  return v_version;
end;
$$;


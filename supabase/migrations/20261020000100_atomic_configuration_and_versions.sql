  where id in (select jsonb_array_elements_text(p_removed_subtopic_ids));
  update public.topics set active = false
  where id in (select jsonb_array_elements_text(p_removed_topic_ids));

  v_version := public.record_assessment_configuration_version();
  return v_version;
end;
$$;

